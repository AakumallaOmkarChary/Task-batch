
public class Datatype {

	
	public static void main(String[] args) {
	
		
		byte  a = 100; // byte stores number from -120 to 127
		short b = 12345 ; // stores num from -32,786 to 32,767
		int   c = 223456; // stores num from -2,147,483,648 to 2,147,483,647 
		long  d = 123456; // stores num from -9,223,372,036 to 9,223,372,036
		float e = 124.089f; // stores fractional nums ,sufficient for storing 6 to 7 decimal
	   double f = 134.09d;// stores fractional num sufficient for storing 15 to 16 decimal values
	   char g = 'H'; // stores a single character or letter 
	 boolean i = true ;// stores true or false values 
	   
	   System.out.println(a);
	   System.out.println(b);
	   System.out.println(c);
	   System.out.println(d);
	   System.out.println(e);
	   System.out.println(f);
	   System.out.println(g);
	   System.out.println(i);
	}

}
