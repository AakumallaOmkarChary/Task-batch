
public class Comparision_operators {
// comparision operations are used to compare two values .this will return a value true or false 
	public static void main(String[] args) {
		int x = 5;
		int y = 3;
	
   	   	   System.out.println(x > y );// return true becose 5 is greater then 3
		   System.out.println( x != y);// not equal 
		   System.out.println(x == y); //equal to 
		   System.out.println(x <= y); // less than or equal to 
		   System.out.println(x = y); //greater than or equal to 
		   System.out.println(x < y); // less than  

	}

}
