
public class Logical_operators {
/* logical operators are used to determine the logic btw variables 
	or values by combing multiple conditions*/
	
	public static void main(String[] args) {
	 int x = 5 ;
	   System.out.println(x < 5 && x< 10); // logical and  returns true if both are true 
	   System.out.println(x < 5 || x < 4); // logical or returns true if one of the statement is true 
	   System.out.println(!(x>3 && x < 10)); // logical not reverse the result true to false visa versa 


	}

}
